import Foundation

/// Готовые замены для тех, кто диктует по-русски с английскими терминами.
///
/// Модель распознаёт русскую речь и записывает англицизмы так, как слышит:
/// «pull request» становится «пул реквест», «Sentry» — «центри». Это не сбой
/// модели, а естественное поведение: внутри русской фразы она и должна писать
/// кириллицей.
///
/// Словарь возвращает терминам их обычный вид. Набор предлагается при первом
/// запуске и правится как угодно — это просто заготовка, а не что-то встроенное.
public enum StarterDictionary {
    /// Термины разработчика.
    public static var developer: [DictionaryReplacement] {
        inflecting.map {
            DictionaryReplacement(
                spoken: $0.0,
                written: $0.1,
                noAcousticBoost: unboostable.contains($0.1)
            )
        }
            + literal.map {
                DictionaryReplacement(
                    spoken: $0.0,
                    written: $0.1,
                    inflects: false,
                    noAcousticBoost: unboostable.contains($0.1)
                )
            }
    }

    /// Термины, чьё кириллическое звучание — обычное русское слово.
    ///
    /// Флаг живёт **в данных заготовки**, а не в фильтре на стороне подсказчика.
    /// Разница не косметическая: убрать список из `VocabularyBoost` и не
    /// проставить признак здесь — значит вернуть `deploy`, `Sentry` и `commit`
    /// в акустику, то есть молча откатить замер, который стоил отдельного дня.
    /// Подробности, почему именно эти три: `DictionaryReplacement.noAcousticBoost`
    /// и docs/benchmarks.md.
    private static let unboostable: Set<String> = ["deploy", "Sentry", "commit"]

    /// Термин в обычном русском написании — со всеми падежами.
    ///
    /// Эти слова в русской речи склоняются: «перед релизом», «после деплоя»,
    /// «без даунтайма».
    ///
    /// Чего здесь намеренно нет: замен, которые совпадают с обычным русским
    /// словом. «Питон», «редис», «докер», «бранч» из набора убраны. Не из
    /// осторожности, а по замеру: на свежих записях они не сработали ни разу
    /// (0 из 5 фраз на каждый термин — модель пишет «допер», «кэшвербис»,
    /// «написан»), зато ломали обычную речь: «питон сжал добычу» превращался в
    /// «Python сжал добычу», «докеры разгружали судно» — в «Docker разгружали
    /// судно». Такую замену человек заводит себе сам, осознанно и для своего
    /// словаря; в заготовке ей не место.
    private static let inflecting: [(String, String)] = [
        // Работа с кодом
        ("пул реквест", "pull request"),
        ("пиар", "PR"),
        ("мёрдж", "merge"),
        ("ребейз", "rebase"),
        ("ревью", "review"),
        ("код ревью", "code review"),

        // Запуск и эксплуатация
        ("деплой", "deploy"),
        ("деплоймент", "deployment"),
        ("билд", "build"),
        ("релиз", "release"),
        ("роллбэк", "rollback"),
        ("даунтайм", "downtime"),
        ("продакшн", "production"),
        ("стейджинг", "staging"),

        // Инструменты
        ("сентри", "Sentry"),
        ("гитхаб", "GitHub"),
        ("кубернетес", "Kubernetes"),
        ("постгрес", "Postgres"),
        ("линтер", "linter"),
        ("экс код", "Xcode"),

        // Разработка
        ("фича флаг", "feature flag"),
        ("хотфикс", "hotfix"),
        ("эндпоинт", "endpoint"),
        ("апи", "API"),
        ("бэкенд", "backend"),
        ("фронтенд", "frontend"),
        ("тайпскрипт", "TypeScript"),
        ("джаваскрипт", "JavaScript"),
        ("свифт", "Swift"),
    ]

    /// Замены, которые берутся только в той форме, в какой записаны.
    ///
    /// Две причины сюда попасть, и обе проверены замером.
    ///
    /// **Это не слово, а огрех распознавания.** Прогон пятнадцати фраз
    /// показал, что модель слышит «пул реквист», «гитхеб», «постгриз», «ход
    /// фикс»; замер записан в docs/benchmarks.md. У обрубка нет падежей, и
    /// склоняемая основа ему только выдумывает совпадения. Проверено: склонение
    /// этих записей не добавило ни одного термина ни на одной записи корпуса.
    ///
    /// **Основа совпадает с обычным русским словом.** Так у «коммита»: с
    /// точностью до безударных гласных он неотличим от «кометы», и склоняемая
    /// основа «комет-» превращала «мы смотрели на комету» в «мы смотрели на
    /// commit». Цена отказа измерена и мала — одна фраза из тридцати
    /// («в коммите» больше не узнаётся), а спасено пятнадцать обычных русских
    /// слов. Само «коммит» и услышанное «комит» по-прежнему узнаются: точная
    /// форма и фонетика работают, склонение — нет.
    ///
    /// Второй проход словаря — фонетический — делает большинство таких записей
    /// ненужными: «диплой» и «депла» узнаются от «деплой» сами. Здесь остались
    /// те, до которых фонетика не дотягивается.
    private static let literal: [(String, String)] = [
        ("пул реквист", "pull request"),
        ("пулреквест", "pull request"),
        ("мердж", "merge"),
        ("коммит", "commit"),
        ("комет", "commit"),
        ("браннич", "branch"),
        ("ребейзнуть", "rebase"),
        ("кот ревью", "code review"),
        ("роллбук", "rollback"),
        ("доунтайм", "downtime"),
        ("продакш", "production"),
        ("центри", "Sentry"),
        ("гитхеб", "GitHub"),
        ("кубернетис", "Kubernetes"),
        ("постгриз", "Postgres"),
        ("линти", "linter"),
        ("иксод", "Xcode"),
        ("x-код", "Xcode"),
        ("фичи-флаг", "feature flag"),
        ("ход фикс", "hotfix"),
        ("бэкинг", "backend"),
        ("фронтинг", "frontend"),
        ("тайп-скрипт", "TypeScript"),
    ]

    /// Замены, которых ещё нет у пользователя.
    ///
    /// Нужно, чтобы предложение «добавить набор» не плодило дубликаты, если
    /// человек уже завёл часть терминов сам.
    public static func missing(from existing: [DictionaryReplacement]) -> [DictionaryReplacement] {
        let known = Set(existing.map { $0.spoken.lowercased() })
        return developer.filter { !known.contains($0.spoken.lowercased()) }
    }
}
